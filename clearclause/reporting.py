def _verdict_color(css_class: str) -> str:
    return {
        "CRITICAL": "#9a1b0a",
        "HIGH": "#c2410c",
        "REVIEW": "#b45309",
        "LOW": "#15803d",
    }.get(css_class, "#1f3a2d")


def _dim_color(value: int) -> str:
    if value >= 70:
        return "#c2410c"
    if value >= 45:
        return "#b45309"
    if value >= 20:
        return "#2f5a40"
    return "#6f8d5c"


def _finding_row(finding: ClauseFinding) -> str:
    return (
        "<tr>"
        f"<td><strong>{html.escape(finding.title)}</strong><br>"
        f"<small style='color:#5a6a62'>{html.escape(finding.category or finding.section_title)}</small></td>"
        f"<td><span class='badge {finding.severity}'>{finding.severity}</span></td>"
        f"<td>{finding.confidence:.0%}</td>"
        f"<td>{html.escape(finding.plain_english)}</td>"
        f"<td>{html.escape(finding.recommendation)}</td>"
        "</tr>"
    )


def _checklist_block(item) -> str:
    actions = "".join(f"<li>{html.escape(action)}</li>" for action in item.actions)
    return (
        f"<div class='checklist-card {item.severity}'>"
        f"<div class='header'><span>#{item.priority} · {html.escape(item.title)}</span>"
        f"<span class='badge {item.severity}'>{item.severity}</span></div>"
        f"<div class='rationale'>{html.escape(item.rationale)}</div>"
        f"<ul>{actions}</ul></div>"
    )


def _benchmark_row(row) -> str:
    return (
        "<tr>"
        f"<td><strong>{html.escape(row.title)}</strong><br>"
        f"<small style='color:#5a6a62'>{html.escape(row.category)}</small></td>"
        f"<td><span class='bench-status {row.status}'>{row.status}</span></td>"
        f"<td>{html.escape(row.fair_standard)}</td>"
        f"<td>{html.escape(row.detected_text)}</td>"
        f"<td>{html.escape(row.gap)}</td>"
        "</tr>"
    )


def _empty_row(cols: int = 5) -> str:
    return (
        f"<tr><td colspan='{cols}' style='text-align:center;color:#5a6a62'>"
        "No rows to display."
        "</td></tr>"
    )
