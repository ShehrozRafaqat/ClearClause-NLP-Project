def findings_to_rows(findings: list[ClauseFinding]) -> list[dict[str, str | int | float]]:
    return [
        {
            "Clause": finding.title,
            "Category": finding.category,
            "Risk": finding.severity,
            "Confidence": round(finding.confidence, 2),
            "Matched Terms": ", ".join(finding.matched_terms),
            "Red Flags": ", ".join(finding.red_flags),
            "Recommendation": finding.recommendation,
            "Evidence": finding.snippet,
        }
        for finding in findings
    ]


def findings_csv(findings: list[ClauseFinding]) -> str:
    output = io.StringIO()
    rows = findings_to_rows(findings)
    writer = csv.DictWriter(output, fieldnames=list(rows[0].keys()) if rows else ["Clause"])
    writer.writeheader()
    writer.writerows(rows)
    return output.getvalue()


def negotiation_markdown(analysis: AnalysisResult) -> str:
    """Plain-text / Markdown negotiation pack for paste-into-email use."""

    checklist = build_checklist(analysis.findings)
    risk = analysis.risk
    verdict = build_verdict(risk)

    lines: list[str] = [
        "# ClearClause Negotiation Pack",
        "",
        f"**Document:** {analysis.document.filename}",
        f"**Risk score:** {risk.score}/100 ({risk.label})",
        f"**Verdict:** {verdict.one_liner}",
        "",
        "## Priority negotiation actions",
        "",
    ]
    if not checklist:
        lines.append("- No actionable high or medium-severity items were detected.")
    for item in checklist:
        lines.append(f"### {item.priority}. {item.title}  ·  {item.severity}")
        lines.append(f"_{item.rationale}_")
        for action in item.actions:
            lines.append(f"- [ ] {action}")
        lines.append("")

    lines.append("## Discovery questions to send the other party")
    from .negotiation import suggested_questions

    for question in suggested_questions(analysis, limit=6):
        lines.append(f"- {question}")
    lines.append("")
    lines.append("_Generated by ClearClause — educational output, not legal advice._")
    return "\n".join(lines)


